import { Scene, LanguageVariant, PublishedVersion } from "@/types";

/**
 * Formats seconds into SRT timestamp: HH:MM:SS,mmm
 */
function formatSRTTime(seconds: number): string {
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);

  const pad = (num: number, size = 2) => String(num).padStart(size, "0");
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(ms, 3)}`;
}

/**
 * Formats seconds into WebVTT timestamp: HH:MM:SS.mmm
 */
function formatVTTTime(seconds: number): string {
  return formatSRTTime(seconds).replace(",", ".");
}

/**
 * Generates an SRT subtitle file from scenes
 */
export function generateSRT(
  scenes: Scene[],
  translatedSegments?: LanguageVariant["translatedSegments"]
): string {
  let currentTime = 0;
  const entries: string[] = [];

  scenes.forEach((scene, index) => {
    const startTime = currentTime;
    const duration = scene.durationSeconds || 20;
    const endTime = startTime + duration;
    currentTime = endTime + 0.5; // slight break between cues

    const translation = translatedSegments?.find((s) => s.sceneId === scene.id);
    const headline = translation?.headline || scene.headline;
    const script = translation?.narration || scene.script;

    entries.push(
      `${index + 1}\n${formatSRTTime(startTime)} --> ${formatSRTTime(endTime)}\n${headline}\n${script}`
    );
  });

  return entries.join("\n\n");
}

/**
 * Generates a WebVTT subtitle file from scenes
 */
export function generateVTT(
  scenes: Scene[],
  translatedSegments?: LanguageVariant["translatedSegments"]
): string {
  let currentTime = 0;
  const entries: string[] = ["WEBVTT\n"];

  scenes.forEach((scene, index) => {
    const startTime = currentTime;
    const duration = scene.durationSeconds || 20;
    const endTime = startTime + duration;
    currentTime = endTime + 0.5;

    const translation = translatedSegments?.find((s) => s.sceneId === scene.id);
    const headline = translation?.headline || scene.headline;
    const script = translation?.narration || scene.script;

    entries.push(
      `${index + 1}\n${formatVTTTime(startTime)} --> ${formatVTTTime(endTime)}\n<v Host>${headline}</v>\n${script}`
    );
  });

  return entries.join("\n\n");
}

/**
 * Generates a full production script with visual directions and cues
 */
export function generateProductionScript(
  projectTitle: string,
  version: string,
  scenes: Scene[]
): string {
  const header = `# ${projectTitle} — Production Script (v${version})
Generated by EasyVideo Change Studio
Date: ${new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}
Total Scenes: ${scenes.length}
======================================================================\n\n`;

  const sceneBlocks = scenes.map((scene) => {
    return `### SCENE ${scene.number}: ${scene.title.toUpperCase()}
[AREA: ${scene.area}] | [EST. DURATION: ${scene.durationSeconds}s] | [STATUS: ${scene.status.toUpperCase()}]

[VISUAL DIRECTION]
${scene.visualDescription}

[ON-SCREEN HEADLINE]
${scene.headline}

[SPOKEN NARRATION]
"${scene.script}"

[GROUNDED SOURCE]
${scene.sourceRef || "Existing verified baseline"}
----------------------------------------------------------------------`;
  });

  return header + sceneBlocks.join("\n\n");
}

/**
 * Generates release notes / changelog markdown for a published version
 */
export function generateChangelog(version: PublishedVersion): string {
  const acceptedScenes = version.snapshot.scenes.filter((s) => s.status === "accepted");
  const preservedScenes = version.snapshot.scenes.filter((s) => s.status !== "accepted");

  return `# Changelog — Version ${version.version}
**Project:** ${version.snapshot.projectTitle}  
**Date:** ${version.date}  
**Author:** ${version.author}  
**Source Document:** ${version.snapshot.sourceFile.name} (${version.snapshot.sourceFile.version})  

---

## Executive Summary
${version.description}

## Summary of Changes (${acceptedScenes.length} Updated Scenes)
${acceptedScenes
  .map(
    (scene) => `### Scene ${scene.number}: ${scene.title}
- **Area:** ${scene.area}
- **New Headline:** "${scene.headline}"
- **Updated Narration:** "${scene.script}"
- **Source Reference:** ${scene.sourceRef || "Policy update"}
`
  )
  .join("\n")}

## Preserved Unchanged Content (${preservedScenes.length} Scenes)
${preservedScenes.map((s) => `- Scene ${s.number}: ${s.title} (${s.area})`).join("\n")}

## Localization Quality Verification
${version.snapshot.languages
  .map(
    (lang) => `- **${lang.name} (${lang.code}):** Reviewed and approved for release.`
  )
  .join("\n")}
`;
}
